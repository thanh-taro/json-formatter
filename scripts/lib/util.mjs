// Shared helpers for build-time code generation (MOD-Build). No dependencies beyond Node.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const rel = (p) => path.relative(ROOT, p);
export const abs = (...p) => path.join(ROOT, ...p);

export const GENERATED_HEADER = (source, generator) =>
  `GENERATED by ${generator} from ${source} — do not edit; run \`pnpm gen\`.`;

/**
 * Writes `content` to `file`, or in check mode compares it with the file on disk.
 * Returns true when the file is (or would be) up to date.
 */
export function emit(file, content, { check }) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (current === content) return true;
  if (check) {
    console.error(`stale: ${rel(file)} (run \`pnpm gen\` and commit the result)`);
    return false;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  console.log(`wrote ${rel(file)}`);
  return true;
}

/** Splits a Markdown table row into trimmed cells, honouring `\|` escapes. */
export function tableCells(line) {
  const t = line.trim();
  if (!t.startsWith('|')) return null;
  const cells = [];
  let cur = '';
  for (let i = 1; i < t.length; i++) {
    const c = t[i];
    if (c === '\\' && t[i + 1] === '|') {
      cur += '|';
      i++;
    } else if (c === '|') {
      cells.push(cur.trim());
      cur = '';
    } else cur += c;
  }
  return cells;
}
